const ACTIONS = ["detect", "list", "find", "info"] as const
type Action = (typeof ACTIONS)[number]

const KINDS = [
  "npm",
  "yarn",
  "yarn-berry",
  "pnpm",
  "bun",
  "cargo",
  "pip",
  "uv",
  "gomod",
  "gemfile",
  "composer",
] as const
type Kind = (typeof KINDS)[number]

const FORMATS = ["lines", "json"] as const
const DEFAULT_LIMIT = 500
const MAX_LIMIT = 5_000
const MAX_BYTES = 64 * 1024 * 1024
const DEP_KINDS = ["prod", "dev", "peer", "optional"] as const
type DepKind = (typeof DEP_KINDS)[number]

export const Parameters = Schema.Struct({
  action: Schema.Literals(ACTIONS).annotate({ description: ACTIONS.join(" | ") }),
  path: Schema.String.check(Schema.isMinLength(1)).annotate({
    description: "Path to the lockfile. Absolute preferred; relative resolves from project dir.",
  }),
  kind: Schema.optional(Schema.Literals(KINDS)).annotate({
    description: "Force a specific parser. Defaults to filename detection.",
  }),
  query: Schema.optional(Schema.String.check(Schema.isMinLength(1))).annotate({
    description: "Exact package name to look up (find).",
  }),
  prefix: Schema.optional(Schema.String).annotate({
    description: "Restrict list results to names starting with this prefix.",
  }),
  dev: Schema.optional(Schema.Boolean).annotate({
    description: "Filter to dev (true) or prod (false) deps. Omit to include all.",
  }),
  direct_only: Schema.optional(Schema.Boolean).annotate({
    description: "list: top-level deps only. Default false.",
  }),
  limit: Schema.optional(
    Schema.Number.check(Schema.isInt(), Schema.isGreaterThanOrEqualTo(1), Schema.isLessThanOrEqualTo(MAX_LIMIT)),
  ).annotate({
    description: `Max entries for list/find. Default ${DEFAULT_LIMIT}.`,
  }),
  format: Schema.optional(Schema.Literals(FORMATS)).annotate({
    description: "Output format: lines (default) or json.",
  }),
})

type Params = Schema.Schema.Type<typeof Parameters>

type Entry = {
  name: string
  version: string
  kind?: DepKind
  scope?: string
  source?: string
  direct?: boolean
}

type Detected = {
  kind: Kind
  lockfile_version?: number | string
}

type Metadata = {
  action: Action
  path: string
  kind?: Kind
  lockfile_version?: number | string
  bytes?: number
  total?: number
  truncated?: boolean
  entries?: Entry[]
  direct?: number
  transitive?: number
  by_kind?: Partial<Record<DepKind, number>>
  total_packages?: number
  sample_names?: string[]
}

const done = (result: Tool.ExecuteResult<Metadata>) => result

