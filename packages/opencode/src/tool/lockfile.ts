const detectKind = (file: string, content: string): Detected => {
  const base = path.basename(file).toLowerCase()
  if (base === "package-lock.json" || base === "npm-shrinkwrap.json") {
    try {
      const j = JSON.parse(content) as { lockfileVersion?: number }
      return { kind: "npm", lockfile_version: j.lockfileVersion }
    } catch {
      return { kind: "npm" }
    }
  }
  if (base === "yarn.lock") {
    if (/__metadata:/.test(content)) return { kind: "yarn-berry" }
    return { kind: "yarn" }
  }
  if (base === "pnpm-lock.yaml" || base === "pnpm-lock.yml") {
    const v = /^lockfileVersion:\s*['"]?([\d.]+)/m.exec(content)?.[1]
    return { kind: "pnpm", lockfile_version: v }
  }
  if (base === "bun.lock") return { kind: "bun" }
  if (base === "cargo.lock") {
    const v = /^version\s*=\s*(\d+)/m.exec(content)?.[1]
    return { kind: "cargo", lockfile_version: v ? Number(v) : undefined }
  }
  if (base === "uv.lock") return { kind: "uv" }
  if (base === "requirements.txt") return { kind: "pip" }
  if (base === "go.sum") return { kind: "gomod" }
  if (base === "gemfile.lock") return { kind: "gemfile" }
  if (base === "composer.lock") return { kind: "composer" }
  // Header-based fallbacks
  if (/^# This file is automatically @generated by Cargo/i.test(content)) return { kind: "cargo" }
  if (/^lockfileVersion:/m.test(content)) return { kind: "pnpm" }
  if (/^# THIS FILE IS GENERATED BY YARN/i.test(content) || /^# yarn lockfile v1/i.test(content))
    return { kind: "yarn" }
  if (/__metadata:\s*\n\s+version: ?\d+/m.test(content)) return { kind: "yarn-berry" }
  if (/^GEM\n/m.test(content) && /^DEPENDENCIES\n/m.test(content)) return { kind: "gemfile" }
  if (/"packages":\s*\[/.test(content) && /"composer":\s*"/.test(content)) return { kind: "composer" }
  if (/^[a-z0-9._-]+==[\d.]+/im.test(content)) return { kind: "pip" }
  if (/^[\w./-]+ v[\d.]+(?:-[\w.]+)?\s+h1:/m.test(content)) return { kind: "gomod" }
  throw new Error("lockfile: cannot detect format from filename or content")
}

